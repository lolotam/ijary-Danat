export function downloadImportTemplate(entity: ImportEntity, locale: "ar" | "en" = "en"): void {
  const suffix = locale === "ar" ? "-ar" : "";
  downloadCsvTemplate(`${entity}-template${suffix}.csv`, importTemplateHeaders[entity], locale);
}
