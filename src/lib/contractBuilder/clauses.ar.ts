/**
 * يكتب إجمالي قيمة العقد رقماً من الفلس، لا من ضرب عشري عائم.
 */
function totalKwd(ctx: ClauseContext): string {
  return formatKwdFromFils(totalValueFils(ctx));
}

/**
 * يكتب القيمة الشهرية رقماً من الفلس بثلاث خانات.
 */
function monthlyKwd(ctx: ClauseContext): string {
  return formatKwdFromFils(toFils(ctx.monthly_value));
}

/**
 * يبني سطر الافتتاح بتاريخ العقد واسم يوم الكويت.
 */
function opening(ctx: ClauseContext): string {
  return `إنه في يوم ${v(ctx.dayName)} الموافق ${v(ctx.contract_date)} م تم الاتفاق بين كل من :-`;
}

const CAPACITY =
  "أقر الطرفان بأهليتهما القانونية للتعاقد والتصرف، وبخلو إرادتيهما من العيوب المبطلة للتصرفات، واتفقا على ما يلي:";

const PERSON_ORDINALS = ["أول", "ثانٍ", "ثالث"] as const;

/**
 * يبني فقرات الطرف الثاني بحسب نوعه، ثم إقرار الأهلية القانونية.
 *
 * A lone person is simply "الطرف الثاني"; the ordinal "(شخص أول)" only
 * distinguishes people once there is more than one of them.
 */
function secondParty(ctx: ClauseContext): string[] {
  if (ctx.second_party_type === "company") {
    const c = ctx.company;
    return [
      `الطرف الثاني: شركة / ${v(c.company_name)}، الكائن مقرها في: ${v(c.company_address)}، ويمثلها قانوناً المفوض بالتوقيع السيد / ${v(c.signatory_name)}، الجنسية: ${v(c.signatory_nationality)}، بالرقم المدني: (${v(c.signatory_civil_id)})، والمقيم في: ${v(c.signatory_address)}.`,
      CAPACITY,
    ];
  }
  const several = ctx.persons.length > 1;
  const lines = ctx.persons.map((person, index) => {
    const label = several ? `الطرف الثاني (شخص ${PERSON_ORDINALS[index]})` : "الطرف الثاني";
    return `${label}: السيد / ${v(person.full_name)}، الجنسية: ${v(person.nationality)}، بالرقم المدني: (${v(person.civil_id)})، والمقيم في: ${v(person.residence_address)}.`;
  });
  return [...lines, CAPACITY];
}

/**
 * يبني التمهيد: العقار والوحدات والنشاط والاسم التجاري من السياق.
 */
function preamble(ctx: ClauseContext): string {
  // With several plots the unit list already names each plot, so the
  // property is plural and "في القسيمة المشار إليها" would contradict it.
  const property = ctx.multiPlot
    ? `المجمعات التجارية الكائنة في محافظة ${v(ctx.governorate)} قطعة (${v(ctx.block)}) – قسائم (${v(ctx.parcel)}) وذلك بقصد استثمار وحداتها`
    : `المجمع التجاري الكائن في محافظة ${v(ctx.governorate)} قطعة (${v(ctx.block)}) – قسيمة (${v(ctx.parcel)}) وذلك بقصد استثمار وحداته`;
  const units = ctx.multiPlot ? ctx.unitList : `${ctx.unitList} في القسيمة المشار إليها`;
  return `حيث إن الطرف الأول يمتلك ${property} بهدف الربح وفقا لأحكام قانون التجارة الكويتي ورغبة من الطرف الثاني في استثمار المحلات أرقام ${units} بغرض استغلالها في نشاط تجاري (${v(ctx.activity)}) تحت الاسم التجاري (${v(ctx.trade_name)}) وبعد المعاينة التامة النافية للجهالة وبعد اطلاعه على المخططات وكروكي الوحدة محل التعاقد وبناء عليه تلاقت إرادة الطرفين على إبرام هذا العقد وقد اتفقا على التعاقد طبقا للبنود الآتية :-`;
}

