/**
 * Localized nationality label for a stored value, falling back to the raw
 * value when it isn't in the list (existing tenants may hold arbitrary text).
 */
export function nationalityLabel(value: string | null | undefined, locale: "ar" | "en"): string {
  if (!value) return "";
  const match = NATIONALITIES.find((nationality) => nationality.value === value);
  return match ? match[locale] : value;
}
